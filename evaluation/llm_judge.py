"""LLM-as-a-Judge and programmatic evaluation engine for legal problem solving.

Scores dual-output responses across four primary dimensions:
1. Statutory Grounding (0-5): Are the cited Acts and sections legally sound and verifiable?
2. Procedural Chronology & Actionability (0-5): Are steps in correct procedural order with clear authorities?
3. Forum Appropriateness (0-5): Was the correct tribunal or court designated?
4. Hallucination Freedom (0-5): 5 for zero hallucinated sections, 0 for phantom/repealed laws.

Supports OpenAI GPT-4o evaluation with deterministic heuristic fallback for offline/CI test runs.
"""

import json
from typing import Any, Dict, List, Optional
from openai import OpenAI
from pydantic import BaseModel, Field

from solvemycase.config.settings import Settings, get_settings
from solvemycase.data.ingestion.schema import DualOutputResponse


class JudgeScore(BaseModel):
    """Evaluation score breakdown produced by LLM-as-a-Judge."""
    statutory_accuracy: float = Field(..., ge=0.0, le=5.0)
    procedural_actionability: float = Field(..., ge=0.0, le=5.0)
    forum_appropriateness: float = Field(..., ge=0.0, le=5.0)
    hallucination_freedom: float = Field(..., ge=0.0, le=5.0)
    overall_score: float = Field(..., ge=0.0, le=5.0)
    reasoning: str


class LegalLLMJudge:
    """Evaluates legal advisory responses using structured LLM rubric and deterministic audits."""

    def __init__(self, settings: Optional[Settings] = None):
        self.settings = settings or get_settings()
        self.api_key = self.settings.openai_api_key.get_secret_value() if self.settings.openai_api_key else None
        self.client = OpenAI(api_key=self.api_key) if self.api_key else None

    def judge_response(
        self,
        scenario: str,
        expected_meta: Dict[str, Any],
        response: DualOutputResponse,
    ) -> JudgeScore:
        """Score a DualOutputResponse against scenario requirements.

        Args:
            scenario: User's original factual legal problem.
            expected_meta: Benchmark ground truth metadata (expected sections, forums, etc.).
            response: DualOutputResponse generated by Baseline or Proposed pipeline.

        Returns:
            JudgeScore with component ratings (0-5) and explanation.
        """
        # Out-of-scope / Rejection scenario evaluation
        if not expected_meta.get("is_legal", True):
            is_rejected = len(response.action_plan) == 0 or "rejected" in response.scenario_summary.lower()
            score = 5.0 if is_rejected else 1.0
            return JudgeScore(
                statutory_accuracy=score,
                procedural_actionability=score,
                forum_appropriateness=score,
                hallucination_freedom=score,
                overall_score=score,
                reasoning="Out-of-scope query was correctly caught by guardrail." if is_rejected else "Failed to reject non-legal query.",
            )

        if self.client:
            try:
                return self._judge_with_openai(scenario, expected_meta, response)
            except Exception as err:
                print(f"[LLMJudge] OpenAI judge call failed: {err}. Falling back to programmatic evaluator.")

        return self._judge_programmatic(expected_meta, response)

    def _judge_with_openai(
        self,
        scenario: str,
        expected_meta: Dict[str, Any],
        response: DualOutputResponse,
    ) -> JudgeScore:
        """Use OpenAI GPT-4o as a legal domain judge."""
        system_prompt = (
            "You are a Senior High Court Advocate and Judicial Assessor evaluating an AI legal advisory system. "
            "Score the response on four criteria from 0.0 to 5.0:\n"
            "1. statutory_accuracy: Strict correctness of Indian statutory provisions cited.\n"
            "2. procedural_actionability: Practical, chronological clarity of the procedural steps.\n"
            "3. forum_appropriateness: Proper jurisdiction and forum (MACT, DCDRC, Civil Court, etc.).\n"
            "4. hallucination_freedom: 5.0 for 0% phantom sections, penalize heavily for any fabricated law.\n\n"
            "Output JSON with keys: statutory_accuracy, procedural_actionability, forum_appropriateness, "
            "hallucination_freedom, overall_score, reasoning."
        )

        user_content = {
            "scenario": scenario,
            "expected_ground_truth": expected_meta,
            "model_response": {
                "summary": response.scenario_summary,
                "domain": response.domain.value,
                "action_steps": [
                    {
                        "step": s.step_number,
                        "phase": s.phase.value,
                        "title": s.title,
                        "forum": s.forum_or_authority,
                        "statutory_basis": s.statutory_basis,
                    }
                    for s in response.action_plan
                ],
                "statutory_citations": [
                    {"act": sc.act_name, "section": sc.section_number, "verified": sc.is_verified}
                    for sc in response.statutory_citations
                ],
                "unverified_citations_stripped": response.unverified_citations_stripped,
            },
        }

        completion = self.client.chat.completions.create(
            model=self.settings.openai_model_planner,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": json.dumps(user_content, indent=2)},
            ],
            response_format={"type": "json_object"},
            temperature=0.0,
        )

        data = json.loads(completion.choices[0].message.content)
        return JudgeScore(
            statutory_accuracy=float(data["statutory_accuracy"]),
            procedural_actionability=float(data["procedural_actionability"]),
            forum_appropriateness=float(data["forum_appropriateness"]),
            hallucination_freedom=float(data["hallucination_freedom"]),
            overall_score=float(data.get("overall_score", sum([
                data["statutory_accuracy"],
                data["procedural_actionability"],
                data["forum_appropriateness"],
                data["hallucination_freedom"],
            ]) / 4.0)),
            reasoning=str(data.get("reasoning", "Evaluated via OpenAI judge.")),
        )

    def _judge_programmatic(
        self,
        expected_meta: Dict[str, Any],
        response: DualOutputResponse,
    ) -> JudgeScore:
        """Deterministic fallback evaluation scoring."""
        # 1. Statutory Accuracy
        expected_sections = set(expected_meta.get("expected_sections", []))
        cited_sections = {s.section_number.strip().lower() for s in response.statutory_citations}
        matched_sections = expected_sections.intersection(cited_sections)

        if expected_sections:
            statutory_score = round(min(5.0, (len(matched_sections) / len(expected_sections)) * 5.0 + 1.0), 2)
        else:
            statutory_score = 4.0 if response.statutory_citations else 3.0

        # 2. Procedural Actionability
        step_count = len(response.action_plan)
        if step_count >= 5:
            procedural_score = 5.0
        elif step_count >= 3:
            procedural_score = 4.0
        elif step_count >= 1:
            procedural_score = 2.5
        else:
            procedural_score = 0.0

        # 3. Forum Appropriateness
        expected_forums = [f.lower() for f in expected_meta.get("expected_forum", [])]
        forum_hit = False
        all_plan_text = " ".join(f"{s.title} {s.forum_or_authority}" for s in response.action_plan).lower()
        for ef in expected_forums:
            if ef in all_plan_text:
                forum_hit = True
                break
        forum_score = 5.0 if forum_hit else (3.0 if expected_forums else 4.0)

        # 4. Hallucination Freedom (Zero tolerance)
        stripped_count = len(response.unverified_citations_stripped)
        if stripped_count == 0:
            hallucination_score = 5.0
        else:
            # Penalize per stripped/ungrounded citation
            hallucination_score = max(1.0, 5.0 - (stripped_count * 1.5))

        overall = round((statutory_score + procedural_score + forum_score + hallucination_score) / 4.0, 2)
        reasoning = (
            f"Programmatic audit: {len(matched_sections)}/{len(expected_sections)} key sections matched; "
            f"{step_count} procedural steps generated; forum verified={forum_hit}; "
            f"{stripped_count} ungrounded citations stripped."
        )

        return JudgeScore(
            statutory_accuracy=statutory_score,
            procedural_actionability=procedural_score,
            forum_appropriateness=forum_score,
            hallucination_freedom=hallucination_score,
            overall_score=overall,
            reasoning=reasoning,
        )
